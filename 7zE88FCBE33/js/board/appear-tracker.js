/* ============================================================
   board/appear-tracker.js — какие карты уже появлялись на экране.
   Раньше анимация "появления" карты навешивалась на КАЖДЫЙ
   рендер для ВСЕХ карт — при любом действии (взял карту, съел
   ход и т.д.) весь стол и вся рука мигали заново. Теперь каждая
   карта проигрывает анимацию появления только один раз — при
   первом рендере, в котором она встретилась.
   ============================================================ */
const seen = new Set();

/* true — карта ещё не появлялась, можно анимировать (и она
   помечается увиденной); false — уже была видна, анимация не нужна. */
export function shouldAnimate(uid){
  if (seen.has(uid)) return false;
  seen.add(uid);
  return true;
}

export function forget(uid){ seen.delete(uid); }

/* Вызывается при входе в новую комнату, чтобы первая раздача карт
   всё же красиво анимировалась, а не считалась "уже виденной". */
export function reset(){ seen.clear(); }
